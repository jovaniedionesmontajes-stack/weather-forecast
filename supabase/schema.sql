-- v1.1 persistent operational alert history
create table if not exists public.weather_alerts (
  id bigint generated by default as identity primary key,
  branch_id uuid not null references public.branches(id) on delete cascade,
  alert_key text not null,
  severity text not null check (severity in ('watch','high')),
  threshold_pct integer not null default 50,
  peak_probability_pct integer not null,
  peak_time timestamptz not null,
  window_start timestamptz not null,
  window_end timestamptz not null,
  source text not null default 'open-meteo',
  status text not null default 'open' check (status in ('open','cleared')),
  detected_at timestamptz not null default now(),
  cleared_at timestamptz,
  last_seen_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  unique(branch_id, alert_key, window_start)
);
create index if not exists weather_alerts_status_idx on public.weather_alerts(status, severity, last_seen_at desc);
create index if not exists weather_alerts_branch_idx on public.weather_alerts(branch_id, detected_at desc);
alter table public.weather_alerts enable row level security;
drop policy if exists "authenticated can read weather alerts" on public.weather_alerts;
create policy "authenticated can read weather alerts" on public.weather_alerts for select to authenticated using (true);
drop policy if exists "managers can manage weather alerts" on public.weather_alerts;
create policy "managers can manage weather alerts" on public.weather_alerts for all to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','manager') and p.is_active)) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','manager') and p.is_active));
